/** 未知の生値はグループ化せず、そのまま返す（シート側に新しい業界が増えても壊さない） */
export function industryGroupOf(rawIndustry: string): string {
  return INDUSTRY_GROUP_MAP[rawIndustry] ?? rawIndustry;
}

/** 実データに存在するグループだけを、定義順で返す */
export function availableIndustryGroups(rawIndustries: readonly string[]): string[] {
  const present = new Set(rawIndustries.map(industryGroupOf));
  const ordered = INDUSTRY_GROUPS.filter((g) => present.has(g)) as string[];
  const unknown = [...present].filter((g) => !(INDUSTRY_GROUPS as readonly string[]).includes(g)).sort();
  return [...ordered, ...unknown];
}
